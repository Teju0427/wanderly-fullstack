import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { getPool, closePool, isDbConfigured } from './pool.js';
import { buildSeedSql } from './seed.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaPath = path.join(here, '..', 'sql', 'schema.sql');
const seedPath = path.join(here, '..', 'sql', 'seed.sql');

/** Split a script into batches on lines that contain only "GO". */
export function splitBatches(script) {
  return script
    .split(/^\s*GO\s*;?\s*$/gim)
    .map((b) => b.trim())
    .filter(Boolean);
}

export async function migrate({ seed = true } = {}) {
  const pool = await getPool();
  const schema = await readFile(schemaPath, 'utf8');
  for (const batch of splitBatches(schema)) {
    await pool.request().batch(batch);
  }
  console.log('[db] schema is up to date');
  if (seed) {
    await pool.request().batch(buildSeedSql());
    console.log('[db] catalog seeded');
  }
}

/** Writes server/sql/seed.sql so it can be run by hand in the Azure Portal Query editor. */
export async function writeSeedFile() {
  const header =
    '/* Generated by `npm run db:seed-sql` from the files in src/data. Run AFTER schema.sql.\n   Idempotent: re-running updates the catalog in place. */\n\n';
  await writeFile(seedPath, header + buildSeedSql() + '\nGO\n', 'utf8');
  console.log(`[db] wrote ${path.relative(process.cwd(), seedPath)}`);
}

// CLI: `node server/db/migrate.js` or `node server/db/migrate.js --write-seed`
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await import('dotenv/config');
  try {
    if (process.argv.includes('--write-seed')) {
      await writeSeedFile();
    } else {
      if (!isDbConfigured()) {
        console.error('Set DB_SERVER / DB_NAME / DB_USER / DB_PASSWORD (see .env.example) first.');
        process.exit(1);
      }
      await migrate({ seed: !process.argv.includes('--no-seed') });
    }
  } catch (e) {
    console.error('[db] migration failed:', e.message);
    process.exitCode = 1;
  } finally {
    await closePool();
  }
}
